def calcular_bomba_riego():
    print("--- CÁLCULO BOMBA SUMERGIBLE PARA RIEGO POR GOTEO ---")

    # Datos agronómicos
    num_plantas = float(input("Número de plantas (ej. 10): "))
    goteros_por_planta = float(input("Número de goteros por planta (pon 8 para llegar a 128L en 8h): "))
    caudal_gotero_lh = float(input("Caudal de cada gotero en Litros/hora (ej. 2): "))

    # Datos hidráulicos
    altura_impulsion_m = float(input("Altura de impulsión (Metros hacia arriba desde la bomba al terreno): "))
    distancia_horizontal_m = float(input("Distancia horizontal total de la tubería principal (Metros): "))
    diametro_mm = float(input("Diámetro interno de la tubería (en milímetros, ej. 16 para manguera de 1/2 pulgada): "))
    presion_trabajo_bar = float(input("Presión de trabajo de los goteros (en Bar, usualmente 1 o 1.5): "))

    # Cálculos de Caudal Total
    # El caudal que importa para la bomba es la suma de TODOS los goteros funcionando al mismo tiempo
    caudal_total_lh = num_plantas * goteros_por_planta * caudal_gotero_lh
    caudal_total_ls = caudal_total_lh / 3600  # Convertir a litros por segundo
    caudal_m3s = caudal_total_ls / 1000       # Convertir a m3 por segundo para la fórmula

    diametro_m = diametro_mm / 1000.0
    longitud_total = altura_impulsion_m + distancia_horizontal_m

    # Cálculo de pérdidas por fricción
    hf = perdidas_friccion_hazen_williams(caudal_m3s, diametro_m, longitud_total)

    # Convertir Bar a Metros de Columna de Agua (m.c.a). 1 Bar = 10.197 m.c.a
    h_presion = presion_trabajo_bar * 10.197

    # Altura Dinámica Total (ADT)
    adt = altura_impulsion_m + hf + h_presion

    print("\n--- RESULTADOS BOMBA DE RIEGO ---")
    print(f"Caudal total requerido del sistema: {caudal_total_lh:.2f} Litros/hora ({caudal_total_ls:.4f} Litros/segundo)")
    print(f"Pérdidas por fricción estimadas: {hf:.2f} metros")
    print(f"Presión necesaria para abrir los goteros: {h_presion:.2f} metros ({presion_trabajo_bar} Bar)")
    print(f"Altura Dinámica Total (ADT) requerida: {adt:.2f} metros")
    print(f"-> Necesitas buscar una bomba sumergible que entregue {adt:.2f} metros de altura a un caudal de {caudal_total_lh:.2f} l/h.")

# Ejecutar el cálculo inmediatamente
calcular_bomba_riego()