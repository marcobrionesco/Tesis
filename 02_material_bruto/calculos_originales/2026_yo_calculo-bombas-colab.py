def calcular_caudal(litros, tiempo_minutos):
    """Calcula el caudal en m3/s y Litros/s"""
    litros_por_segundo = litros / (tiempo_minutos * 60)
    m3_por_segundo = litros_por_segundo / 1000
    return m3_por_segundo, litros_por_segundo

def perdidas_friccion_hazen_williams(caudal_m3s, diametro_m, longitud_m, coef_c=140):
    """
    Calcula las pérdidas por fricción usando la fórmula de Hazen-Williams.
    coef_c = 140 es el valor estándar para tuberías de PVC.
    """
    if caudal_m3s == 0 or diametro_m == 0:
        return 0
    # Fórmula de Hazen-Williams para pérdida de carga (metros)
    hf = 10.67 * longitud_m * ((caudal_m3s / coef_c)**1.852) / (diametro_m**4.87)
    return hf

def calcular_bomba_transversal():
    print("--- CÁLCULO BOMBA TRANSVERSAL (SUPERFICIE) ---")
    volumen_l = float(input("¿Cuántos litros deseas llenar?: "))
    tiempo_min = float(input("¿En cuántos minutos deseas llenarlo?: "))
    altura_succion_m = float(input("Altura de succión (Metros desde el agua hasta la bomba): "))
    altura_impulsion_m = float(input("Altura de impulsión (Metros hacia arriba desde la bomba al destino final): "))
    distancia_horizontal_m = float(input("Distancia horizontal de impulsión (Metros): "))
    diametro_mm = float(input("Diámetro interno de la tubería (en milímetros, ej. 25 para 1 pulgada): "))
    presion_final_bar = float(input("Presión requerida al final (en Bar, pon 0 si es descarga libre): "))

    # Cálculos de flujo
    q_m3s, q_ls = calcular_caudal(volumen_l, tiempo_min)
    diametro_m = diametro_mm / 1000.0

    # La longitud total de la tubería suma la succión, la impulsión vertical y el recorrido horizontal
    longitud_total = altura_succion_m + altura_impulsion_m + distancia_horizontal_m

    # Cálculo de pérdidas por fricción
    hf = perdidas_friccion_hazen_williams(q_m3s, diametro_m, longitud_total)

    # Convertir Bar a Metros de Columna de Agua (m.c.a). 1 Bar = 10.197 m.c.a
    h_presion = presion_final_bar * 10.197

    # Altura Dinámica Total (ADT)
    adt = altura_succion_m + altura_impulsion_m + hf + h_presion

    print("\n--- RESULTADOS BOMBA TRANSVERSAL ---")
    print(f"Caudal requerido: {q_ls:.2f} Litros/segundo ({q_m3s*3600:.2f} m3/hora)")
    print(f"Pérdidas por fricción en tubería: {hf:.2f} metros")
    print(f"Altura Dinámica Total (ADT) requerida: {adt:.2f} metros")
    print(f"-> Necesitas buscar una bomba que levante al menos {adt:.2f} metros a un caudal de {q_ls:.2f} l/s.\n")

