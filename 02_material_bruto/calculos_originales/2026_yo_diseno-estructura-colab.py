# ==============================================================================
# 2. RESOLUCIÓN DE ECUACIONES DE LA VIGA CONTINUA (2 Vanos simétricos con qu)
# ==============================================================================
# Al ser una viga hiperestática con carga uniforme 'w_u', resolvemos mediante
# métodos clásicos de resistencia de materiales (Teorema de los tres momentos):

# A. Momentos Flectores Críticos
# - Momento negativo máximo (ocurre en las fibras superiores justo sobre el pilar central):
