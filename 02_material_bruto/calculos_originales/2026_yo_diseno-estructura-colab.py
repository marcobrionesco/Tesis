sigma_sn_min = sigma_min if sigma_min > 0 else 0.0

print(f"-> Presión máxima sobre el suelo: {sigma_max:.2f} kN/m² (< q_adm = {q_admisible_suelo} kN/m²)")
print(f"-> Presión mínima sobre el suelo: {sigma_sn_min:.2f} kN/m²\n")




# --- 4. DISEÑO DE LA PLACA BASE DE ACERO (AISC 360 / NCh427/1) ---
print("--- 2. DIMENSIONAMIENTO DE LA PLACA BASE DE ACERO ---")
# Proponemos una placa base cuadrada exterior
lado_placa = 0.300          # 30 cm de lado (m)
area_placa = lado_placa**2

# Resistencia nominal al aplastamiento del hormigón (Phi = 0.65 s/ DS 60)
phi_aplastamiento = 0.65
Pp_nominal = 0.85 * f_c_hormigon * area_placa
Phi_Pp = phi_aplastamiento * Pp_nominal

# Presión última actuante bajo la placa debido a flexocompresión LRFD
W_placa = (lado_placa**3) / 6
fp_max = (Pu_ultima / area_placa) + (Mu_sismico / W_placa)

print(f"-> Resistencia de diseño al aplastamiento hormigón (Phi*Pp): {Phi_Pp:.2f} kN")
print(f"-> Presión máxima solicitante en la placa (fp_max): {fp_max:.2f} kN/m²")

# Cálculo del espesor de placa requerido (Fórmula de flexión en voladizo m, n)
m_voladizo = (lado_placa - dim_pilar) / 2
# Momento último en la sección crítica de la placa
Mu_placa = fp_max * (m_voladizo**2) / 2
# Espesor mínimo por flexión de placa (Phi = 0.90)
t_placa_req = np.sqrt((4 * Mu_placa) / (0.90 * Fy_acero))

print(f"-> Espesor mínimo de placa base requerido por cálculo: {t_placa_req*1000:.1f} mm")
print(f"   * Se debe especificar comercialmente una placa de: {np.ceil(t_placa_req*1000/2)*2:.0f} mm (e.g., 16 mm o 20 mm).\n")


# --- 5. DISEÑO DE PERNOS DE ANCLAJE (Tracción Sísmica Extrema) ---
print("--- 3. VERIFICACIÓN DE PERNOS DE ANCLAJE ---")
# Configuración: 4 pernos en las esquinas. Distancia entre pernos (eje a eje) d_b = 22 cm
dist_pernos = 0.220
num_pernos_tension = 2

# Tracción última por pilar considerando el par volcante sismico
# T_bolt = (Mu / dist_pernos) - (Pu_ultima / 2) -> repartido en los pernos de un lado
Tu_total_lado = (Mu_sismico / dist_pernos) - (Pu_ultima / 2)
Tu_perno = max(0.0, Tu_total_lado / num_pernos_tension)

# Capacidad de un perno estándar de 3/4" (A325 / Grado 8.8) s/ NCh427
# Diámetro de 19.05 mm -> Área nominal = 285 mm² = 0.000285 m²
A_barr = 0.000285
phi_tension_perno = 0.75
Tn_perno = 0.75 * 550000 * A_barr # Fu ~ 550 MPa para pernos certificados
Phi_Tn = phi_tension_perno * Tn_perno

print(f"-> Fuerza de tracción última solicitante por perno: {Tu_perno:.2f} kN")
print(f"-> Resistencia de diseño a la tracción del perno (3/4\"): {Phi_Tn:.2f} kN")

