# Carga lineal viva (L) debido a los 3 estanques cilíndricos repartidos a lo largo
w_L = (P_estanque_kN * 3) / L_total # kN/m

# Combinación de carga última LRFD para diseño de resistencia (NCh3171)
# qu = 1.2 * D + 1.6 * L
