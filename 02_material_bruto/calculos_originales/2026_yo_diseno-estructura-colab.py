# Conversión a fuerza (kN) -> 1 kgf * 9.81 / 1000 = kN
P_estanque_kN = (peso_total_estanque_kg * 9.81) / 1000

print("--- 1. CONTROL DE CARGAS DE LOS ESTANQUES ---")
print(f"-> Volumen de agua por estanque: {volumen_agua:.3f} m³")
print(f"-> Peso de agua por estanque: {peso_agua:.1f} kg")
print(f"-> Peso TOTAL de 1 estanque lleno: {peso_total_estanque_kg:.1f} kg")
print(f"-> Fuerza puntual equivalente por estanque: {P_estanque_kN:.2f} kN\n")

# ==============================================================================
# 3. CONFIGURACIÓN DEL SISTEMA DE PISO (Madera s/ NCh1198:2024)
# ==============================================================================
# Para soportar este peso, la plancha de madera no puede volar en el aire;
