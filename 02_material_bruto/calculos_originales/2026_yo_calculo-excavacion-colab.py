import matplotlib.pyplot as plt
import numpy as np

def calcular_y_guardar_zanja(distancias, cotas_terreno, cota_inicio, pendiente_pct, diametro_m, tapada_minima):
    # --- 1. PREPARAR EL TEXTO DEL REPORTE ---
    texto_reporte = "="*102 + "\n"
    texto_reporte += "ANÁLISIS DE AUTOLAVADO Y PENDIENTE\n"
    texto_reporte += "="*102 + "\n"

    if pendiente_pct < 1.0:
        texto_reporte += f"⚠️ RIESGO DE OBSTRUCCIÓN: Pendiente muy baja ({pendiente_pct}%). El agua no tendrá fuerza tractiva para arrastrar sólidos (autolavado).\n"
    elif pendiente_pct > 3.0:
        texto_reporte += f"⚠️ RIESGO DE SEPARACIÓN SÓLIDOS/LÍQUIDOS: Pendiente muy alta ({pendiente_pct}%). El líquido fluirá muy rápido dejando los sólidos atrás.\n"
    else:
        texto_reporte += f"✅ AUTOLAVADO ÓPTIMO: Pendiente del {pendiente_pct}% adecuada para diámetros sanitarios típicos.\n"

    texto_reporte += "\n"
    texto_reporte += "="*102 + "\n"
    texto_reporte += f"{'Dist (m)':<10} | {'Cota Terreno (m)':<17} | {'Cota Fondo Tubo (m)':<20} | {'Excav Total (m)':<16} | {'Tapada (m)':<11} | {'Estado'}\n"
    texto_reporte += "="*102 + "\n"

    # --- 2. CÁLCULOS ---
    pendiente_dec = pendiente_pct / 100.0
    cotas_tubo_fondo = []
    cotas_tubo_tope = []
    excavaciones = []
    tapadas = []

    for i in range(len(distancias)):
        L = distancias[i]
        z_terr = cotas_terreno[i]

        z_tubo = cota_inicio - (L * pendiente_dec)
        z_clave = z_tubo + diametro_m

        excavacion = z_terr - z_tubo
        tapada = z_terr - z_clave

        if tapada < 0:
            estado = "🚨 TUBO EN EL AIRE"
        elif tapada < tapada_minima:
            estado = "⚠️ TAPADA INSUFICIENTE"
        else:
            estado = "✅ OK"

        cotas_tubo_fondo.append(z_tubo)
        cotas_tubo_tope.append(z_clave)
        excavaciones.append(excavacion)
        tapadas.append(tapada)

        texto_reporte += f"{L:<10.2f} | {z_terr:<17.2f} | {z_tubo:<20.2f} | {excavacion:<16.2f} | {tapada:<11.2f} | {estado}\n"

    # --- 3. CREAR EL LIENZO (TEXTO + GRÁFICO) ---
    fig = plt.figure(figsize=(13, 10))

    # Área superior para el texto
    ax_texto = fig.add_axes([0.05, 0.65, 0.9, 0.3])
    ax_texto.axis('off')
    # El tamaño de fuente (fontsize=10) se ajusta para que entre perfecto
    ax_texto.text(0, 1, texto_reporte, fontfamily='monospace', fontsize=10, va='top', ha='left')

    # Área inferior para el gráfico de la zanja
    ax_plot = fig.add_axes([0.05, 0.05, 0.9, 0.55])

    # Dibujar Terreno
    ax_plot.plot(distancias, cotas_terreno, label="Nivel de Terreno", color="saddlebrown", marker='o', linewidth=2)

    # Dibujar Tubo (Fondo y Tope)
    ax_plot.plot(distancias, cotas_tubo_fondo, label="Fondo Tubo", color="blue", linestyle="-", linewidth=2)
    ax_plot.plot(distancias, cotas_tubo_tope, label="Tope Tubo", color="blue", linestyle="--", linewidth=1.5)

    # Rellenar áreas para visualizar la zanja
    ax_plot.fill_between(distancias, cotas_terreno, cotas_tubo_tope, color="wheat", alpha=0.5, label="Tierra (Tapada)")

    # Marcar visualmente problemas de tapada
    for i in range(len(distancias)):
        if tapadas[i] < tapada_minima:
            ax_plot.scatter(distancias[i], cotas_tubo_tope[i], color="red", s=100, zorder=5)
            ax_plot.annotate("Alerta", (distancias[i], cotas_tubo_tope[i] + 0.2), color="red", fontweight="bold")

    ax_plot.set_title(f"Perfil de Excavación Sanitaria - Pendiente {pendiente_pct}%", fontsize=14)
    ax_plot.set_xlabel("Distancia desde inicio (m)", fontsize=12)
    ax_plot.set_ylabel("Elevación / Cota (m)", fontsize=12)
    ax_plot.legend(loc="upper right")
    ax_plot.grid(True, linestyle=':', alpha=0.7)

    # --- 4. GUARDAR LA IMAGEN ---
    nombre_archivo = "reporte_excavacion_107m.png"
    plt.savefig(nombre_archivo, dpi=300, bbox_inches='tight', facecolor='white')
    print(f"✅ ¡Imagen generada y guardada exitosamente como '{nombre_archivo}'!")

    # Mostrar en pantalla
    plt.show()

